export const generateHistoricalTelemetry = (): TelemetryHistoryPoint[] => {
  const points: TelemetryHistoryPoint[] = [];
  const now = Date.now();
  for (let i = 30; i >= 0; i--) {
    const time = new Date(now - i * 5000);
    const timeStr = time.toTimeString().split(' ')[0];
    points.push({
      timestamp: timeStr,
      replicationLagBytes: 800 + Math.floor(Math.random() * 600),
      rpoMs: 30 + Math.floor(Math.random() * 30),
      rps: Number((50 + Math.random() * 10).toFixed(1)),
      http5xx: Number((Math.random() * 0.05).toFixed(3)),
      rttLatencyMs: Number((23 + Math.random() * 3).toFixed(1)),
      jitterMs: Number((0.8 + Math.random() * 0.8).toFixed(2)),
      packetLoss: 0.0,
    });
  }
  return points;
};

